def test_真道规则链执行且两模式处理完全相同消息(同口径结果):
    """证据：理由带 评估.道 前缀（真 .道 规则链）；两模式外部编号集合完全相同。"""
    基线 = 同口径结果["基线结果"]
    批处理 = 同口径结果["批处理结果"]
    assert len(基线) == 300, f"基线采样数应为 300，实际 {len(基线)}"
    assert len(批处理) == 300, f"批处理采样数应为 300，实际 {len(批处理)}"

    基线编号 = {行["外部编号"] for 行 in 基线}
    批编号 = {行["外部编号"] for 行 in 批处理}
    assert 基线编号 == 批编号, "两模式处理的不是完全相同的 300 条消息（外部编号集合不一致）"

    显式理由 = [行["理由"] for 行 in 基线 if 行["类别"] == "显式" and 行["理由"]]
    assert len(显式理由) == 20, f"基线显式请求理由条数应为 20，实际 {len(显式理由)}"
    assert all(理由.startswith("关键词规则：") for 理由 in 显式理由), (
        "存在非 评估.道 产生的理由，疑似 Python 等价复刻而非真 .道 规则链"
    )
    print(f"\n真 .道 证据：20/20 显式理由均以「关键词规则：」开头；两模式各 {len(基线编号)} 条同批消息")


