def test_两模式逐条耗时列表同口径可比(同口径结果):
    """核心修复：两模式都从 300 个「单条耗时」算分位，量纲一致、可直接相除。

    第八/十一轮的缺陷正在于 p95 用单条耗时、基线却用整轮合计墙钟，二者不可除；
    本用例断言两份列表都是 300 个非负有限数，且分位确实由该列表算出。
    """
    基线耗时 = 同口径结果["基线耗时"]
    批处理耗时 = 同口径结果["批处理耗时"]
    assert len(基线耗时) == 300, f"基线逐条耗时列表长度应为 300，实际 {len(基线耗时)}"
    assert len(批处理耗时) == 300, f"批处理逐条耗时列表长度应为 300，实际 {len(批处理耗时)}"
    assert all(0 <= 耗时 < float("inf") for 耗时 in 基线耗时 + 批处理耗时), (
        "逐条耗时必须是非负有限毫秒数"
    )

    基线分位 = 同口径结果["基线分位"]
    批处理分位 = 同口径结果["批处理分位"]
    assert 基线分位["p95"] == sorted(基线耗时)[int(0.95 * 300)], "基线 p95 未由逐条耗时列表算出"
    assert 批处理分位["p95"] == sorted(批处理耗时)[int(0.95 * 300)], "批处理 p95 未由逐条耗时列表算出"

    print("\n================ 同口径 p50/p95/max（逐条耗时，毫秒） ================")
    print(f"  单会话基线（1 进程串行 300 条）：p50={基线分位['p50']:.4f} "
          f"p95={基线分位['p95']:.4f} max={基线分位['max']:.4f}")
    print(f"  批处理（4 进程并发 4×75 条）：p50={批处理分位['p50']:.4f} "
          f"p95={批处理分位['p95']:.4f} max={批处理分位['max']:.4f}")
    print("====================================================================")


@pytest.mark.xfail(
    strict=False,
    reason="p95 ≤ 基线 60% 为本轮判定目标：达成 xpass、未达成 xfail，两者均如实记录；"
           "本机真子进程并发不代表生产真实流量，不伪造数据、不改口径硬凑",
)
def test_p95同口径比值不高于基线60百分比(同口径结果):
    """同口径判定：p95批处理 / p95基线 <= 0.60；未达成由 xfail(strict=False) 如实标注。"""
    基线分位 = 同口径结果["基线分位"]
    批处理分位 = 同口径结果["批处理分位"]
    比值 = 批处理分位["p95"] / 基线分位["p95"] if 基线分位["p95"] else float("inf")

    print("\n==================== 同口径 p95 比值判定报告 ====================")
    print("口径：两模式均从 300 个单条耗时算 p95（非整轮合计墙钟），可直接相除。")
    print(f"负载：完全相同 300 条（280 噪音 + 20 显式）；"
          f"基线 1 进程串行、批处理 4 进程并发；共 {同口径结果['子进程数']} 个真 .道 子进程。")
    print(f"  p95 基线={基线分位['p95']:.4f}ms；p95 批处理={批处理分位['p95']:.4f}ms")
    print(f"  实测 p95 比值 = {比值:.2%}（目标 ≤ 60.00%）"
          f"（{'达成' if 比值 <= 0.6 else '未达成，xfail 如实记录'}）")
    print("【端到端墙钟（毫秒，旁证，不参与相除）】")
    print(f"  基线={同口径结果['基线墙钟毫秒']:.2f}；"
          f"批处理={同口径结果['批处理墙钟毫秒']:.2f}；"
          f"4 块进程墙钟={[round(值, 2) for 值 in 同口径结果['批墙钟列表']]}")
    print("【诚实注记】同口径逐条耗时可比，弥补第八/十一轮 p95 与整轮基线不可除的缺陷；")
    print("           本机真子进程 ≠ 生产真实流量（本地构造事件、无真实 webhook/网络/ollama），")
    print("           即使比值达成也不勾选 PRD §12 任何 DoD 项。")
    print("===============================================================")

    assert 批处理分位["p95"] <= 0.6 * 基线分位["p95"], (
        f"同口径 p95 比值未达 60%：批处理 p95={批处理分位['p95']:.4f}ms，"
        f"基线 p95={基线分位['p95']:.4f}ms，实测比值 {比值:.2%} > 60.00%"
    )


