"""更夫 Nightwatch — 同口径 p95 判定测试（第十二轮 / 共享契约 §2 C）。

【本测试要补的缺陷】
第八轮 ``test_load_real_concurrency.py`` 与第十一轮 ``test_rule_engine_real_process.py``
留下同一个诚实缺口：p95 取的是**单条判定耗时**，而被对照的基线取的是**整轮合计墙钟**，
两者量纲不同、不可直接相除，于是「p95 ≤ 基线 60%」始终只能观测、无法真正判定。
本测试把两种模式统一到**逐条耗时列表**这一口径上：

- 单会话基线：1 个真 .道 子进程内串行处理 300 条，逐条记录单条耗时（毫秒列表）；
- 批处理：同样 300 条切 4 批，4 个真 .道 子进程并发处理，每条仍记录单条耗时，
  跨子进程汇总成同一份毫秒列表。

两模式都从各自的**逐条耗时列表**算 p50/p95/max（同一口径、可直接相除），
另记端到端墙钟作为旁证，真正判定 ``p95批处理 / p95基线 <= 0.60``。

【真调用链】
``sys.executable`` 启真实 OS 子进程跑 ``源码/main.py``（cwd=``示例/更夫``，
``GENGFU_NO_LLM=1``），工作负载 .道 脚本在 ``tempfile.TemporaryDirectory()`` 内生成，
用 ASCII 环境变量传 JSON 路径，逐条真调 ``创建准入器(白名单).判定(触)`` 与
``创建评估器(规则列表, 策略版本, 语言模型).评估(触, 模式审计)``。
（已只读确认 ``评估.道`` 另导出 ``串行评估(评估器, 触发列表, 模式)``，但它只返回决策列表、
不提供逐条计时，故本工作负载直接逐条调 ``评估()``。）
理由以「关键词规则：」开头只存在于 ``应用层/评估.道``，是真规则链执行的可观测证据。
内置 ``时间戳()`` 是 ``time.perf_counter()``（各进程起点不同），**只用于同进程内差值**，
绝不跨进程传原始值做比较，符合第十二轮规约 §0 的关键陷阱约束。

【硬指标与诚实边界】
噪音误建单 = 0、显式建单 20/20，两模式同时成立。p95 比值未达 0.60 时用
``pytest.xfail(strict=False)`` 如实记录，不伪造数据、不改口径硬凑。
本机真子进程 ≠ 生产真实流量（事件为本地构造、非真实 webhook；无真实网络 / ollama），
**即使比值达成也不勾选 PRD §12 任何 DoD 项**，本测试只证明本地可验证部分已实现。

【测试约定】
一律 ``sys.executable``；禁 ``signal.SIGKILL``，停止用 ``proc.terminate()`` fallback
``proc.kill()``；临时文件随 TemporaryDirectory 自动清理；禁硬编码 ``.venv/bin/python``；
本测试不启网络服务，无需端口（若需要则必须用 0 自动分配）。
"""

